# Impureté de Gini d'un groupe : 1 - (part de légitimes)2 - (part de phishing)2
def gini(nb_legitimes, nb_phishing):
    total = nb_legitimes + nb_phishing
    p0 = nb_legitimes / total
    p1 = nb_phishing / total
    return 1 - p0**2 - p1**2
print("Groupe pur (100 légitimes, 0 phishing) :", round(gini(100, 0), 3))
