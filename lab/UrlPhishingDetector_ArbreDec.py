def extraire_caracteristiques(url):
    """Calcule les COLONNES_URL pour une URL écrite à la main (approximation)."""
    texte = url.strip()
    # Dans le dataset, les URL sont enregistrées SANS "http://" ni "https://".
    texte = re.sub(r"^https?://", "", texte, flags=re.IGNORECASE)
    # On retire un éventuel "/" final ("google.com/" = "google.com").
    texte = texte.rstrip("/")
    # Le domaine : tout ce qui est avant le premier "/", "?" ou ":".
    domaine = re.split(r"[/?:]", texte)[0]
    c = {}
    for nom, caractere in CARACTERES.items():
        c[f"qty_{nom}_url"] = texte.count(caractere)
    c["length_url"] = len(texte)
    for nom in ["dot", "hyphen", "underline", "at"]:
        c[f"qty_{nom}_domain"] = domaine.count(CARACTERES[nom])
    c["qty_vowels_domain"] = sum(domaine.lower().count(v) for v in "aeiou")
    c["domain_length"] = len(domaine)
    c["domain_in_ip"] = int(bool(re.fullmatch(r"\d{1,3}(\.\d{1,3}){3}", domaine)))
    c["server_client_domain"] = int("server" in domaine.lower() or "client" in domaine.lower())
    # Un tableau d'une seule ligne, avec les colonnes dans le bon ordre.
    return pd.DataFrame([c])[COLONNES_URL]

